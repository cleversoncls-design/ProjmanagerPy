export function translate(lang, text, vars) {
  let result = lang === 'es' ? es[text] ?? text : text
  if (vars) {
    for (const [key, value] of Object.entries(vars)) {
      result = result.replaceAll(`{${key}}`, value)
    }
  }
  return result
}
